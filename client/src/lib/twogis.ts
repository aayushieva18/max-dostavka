// Ссылка на 2ГИС для построения маршрута от текущего положения курьера до
// точки заказа. Формат — обычный https-адрес: если на телефоне установлено
// приложение 2ГИС, оно перехватит ссылку и откроется само; если нет —
// откроется сайт 2ГИС с тем же маршрутом. Точка "откуда" оставлена пустой —
// 2ГИС сам возьмёт текущее местоположение устройства.
export function build2gisRouteLink(point: { lat: number; lon: number }): string {
  return `https://2gis.ru/directions/tab/car/points/|${point.lon},${point.lat}`;
}
